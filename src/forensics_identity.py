mdp= pd.read_csv(r'D:\Chua files\Said_mol2_files\merged_descriptors_with_pic50.csv', low_memory=False, usecols=['PIC50'])
d2 = pd.read_csv(r'D:\Chua files\MDS_analysis\data_model\2.csv', low_memory=False)
d2c= pd.read_csv(r'D:\Chua files\MDS_analysis\data_model\2_cleaned.csv', low_memory=False)

print("### JDes_output3 'Name' column, first 15 and last 5")
print(list(j3['Name'].head(15)))
