d3 = [c for c in j3.columns if c != 'Name']
d2c_ = [c for c in j2.columns if c != 'PIC50']
print("### descriptor-column identity between JDes_output3 and JDes_output2")
print("same set:", set(d3) == set(d2c_), " same order:", d3 == d2c_)
print("only in J3:", sorted(set(d3)-set(d2c_))[:10])
print("only in J2:", sorted(set(d2c_)-set(d3))[:10])
print()

# do the numeric values match row-for-row?
A = j3[d3].to_numpy(dtype=float)
B = j2[d3].to_numpy(dtype=float)
both = ~(np.isnan(A) | np.isnan(B))
print("### row-order value agreement J3 vs J2 (nan-aware)")
print("cells compared:", both.sum(), " max abs diff:", np.nanmax(np.abs(A[both]-B[both])))
print("nan pattern identical:", np.array_equal(np.isnan(A), np.isnan(B)))
print()

print("### PIC50 sources")
print("J2 PIC50   :", j2['PIC50'].describe().round(4).to_dict())
print("mergedPIC50:", mdp['PIC50'].describe().round(4).to_dict())
print("2.csv PIC50:", d2['PIC50'].describe().round(4).to_dict())
print("identical J2 vs merged:", np.allclose(j2['PIC50'], mdp['PIC50']))
print("identical J2 vs 2.csv :", np.allclose(j2['PIC50'], d2['PIC50']))
print()

print("### NaN structure in JDes_output3")
nanc = j3[d3].isna().sum()
nanc = nanc[nanc>0].sort_values(ascending=False)
print("cols with NaN:", len(nanc))
print(nanc.to_dict())
print()

print("### imputation check: does J2_imputed differ from J2 only at NaN cells?")
C = j2i[d3].to_numpy(dtype=float)
nanmask = np.isnan(B)
print("non-nan cells unchanged:", np.allclose(B[~nanmask], C[~nanmask]))
print("filled values sample:", C[nanmask][:8])
# was it column mean/median?
colmeans = np.nanmean(B, axis=0)
colmeds  = np.nanmedian(B, axis=0)
ii, jj = np.where(nanmask)
print("matches col MEAN  :", np.allclose(C[nanmask], colmeans[jj], atol=1e-6))
print("matches col MEDIAN:", np.allclose(C[nanmask], colmeds[jj], atol=1e-6))
print("all filled == 0   :", np.allclose(C[nanmask], 0))
print()

print("### 2.csv vs 2_cleaned.csv rows (isolation-forest removal)")
